export const getTranslation = (lang, key) => {
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.de[key] || key;
};

/**
 * Liest die aktuelle Sprache aus dem globalen Store und liefert eine `t(key)`
 * Übersetzungsfunktion. Re-rendert Komponenten automatisch, wenn `lang` sich ändert
 * (z. B. über den Sprachumschalter in der Navbar).
 */
export function useTranslation() {
  const lang = useStore((state) => state.lang);
  const t = (key) => getTranslation(lang, key);
  return { t, lang };
}
